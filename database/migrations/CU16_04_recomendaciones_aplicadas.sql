-- CU16 etapa final. Registro idempotente de recomendaciones UML aplicadas.
-- Migracion aditiva: no modifica diagramas, mensajes ni usuarios existentes.

CREATE TABLE IF NOT EXISTS public.recomendacion_aplicada_proyecto (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recomendacion_id character varying(36) NOT NULL,
    mensaje_ia_id bigint NOT NULL,
    proyecto_id bigint NOT NULL,
    diagrama_id bigint NOT NULL,
    aplicada_por_id bigint NOT NULL,
    tipo_cambio character varying(40) NOT NULL,
    version_origen bigint NOT NULL,
    version_resultado bigint NOT NULL,
    fecha_aplicacion timestamp(6) without time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CONSTRAINT uk_recomendacion_aplicada_mensaje UNIQUE (mensaje_ia_id, recomendacion_id),
    CONSTRAINT fk_recomendacion_aplicada_mensaje FOREIGN KEY (mensaje_ia_id) REFERENCES public.mensaje_chat_proyecto(id),
    CONSTRAINT fk_recomendacion_aplicada_proyecto FOREIGN KEY (proyecto_id) REFERENCES public.proyecto(id),
    CONSTRAINT fk_recomendacion_aplicada_diagrama FOREIGN KEY (diagrama_id) REFERENCES public.diagrama(id),
    CONSTRAINT fk_recomendacion_aplicada_usuario FOREIGN KEY (aplicada_por_id) REFERENCES public.usuario(id)
);

CREATE INDEX IF NOT EXISTS idx_recomendacion_aplicada_diagrama
    ON public.recomendacion_aplicada_proyecto (diagrama_id, fecha_aplicacion);
