-- CU16 etapa 1. Migración aditiva e idempotente para PostgreSQL.
-- No elimina ni modifica datos o tablas existentes.

CREATE TABLE IF NOT EXISTS public.mensaje_chat_proyecto (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id bigint NOT NULL,
    usuario_emisor_id bigint,
    tipo_emisor character varying(16) NOT NULL,
    contenido text NOT NULL,
    fecha_hora timestamp(6) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado character varying(24) NOT NULL,
    correlacion_id character varying(36) NOT NULL,
    metadatos text,
    CONSTRAINT fk_mensaje_chat_proyecto
        FOREIGN KEY (proyecto_id) REFERENCES public.proyecto(id),
    CONSTRAINT fk_mensaje_chat_usuario_emisor
        FOREIGN KEY (usuario_emisor_id) REFERENCES public.usuario(id) ON DELETE SET NULL,
    CONSTRAINT ck_mensaje_chat_tipo_emisor
        CHECK (tipo_emisor IN ('USUARIO', 'IA', 'SISTEMA')),
    CONSTRAINT ck_mensaje_chat_estado
        CHECK (estado IN ('ENVIADO', 'PROCESANDO', 'COMPLETADO', 'ERROR')),
    CONSTRAINT ck_mensaje_chat_emisor_real
        CHECK (tipo_emisor <> 'USUARIO' OR usuario_emisor_id IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS idx_mensaje_chat_proyecto_fecha
    ON public.mensaje_chat_proyecto (proyecto_id, fecha_hora, id);

CREATE INDEX IF NOT EXISTS idx_mensaje_chat_correlacion
    ON public.mensaje_chat_proyecto (correlacion_id);

-- Hibernate puede haber creado la tabla antes de ejecutar este script. En ese
-- caso se completa de forma segura la regla que exige emisor real al usuario.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'ck_mensaje_chat_emisor_real'
          AND conrelid = 'public.mensaje_chat_proyecto'::regclass
    ) THEN
        ALTER TABLE public.mensaje_chat_proyecto
            ADD CONSTRAINT ck_mensaje_chat_emisor_real
            CHECK (tipo_emisor <> 'USUARIO' OR usuario_emisor_id IS NOT NULL);
    END IF;
END
$$;
