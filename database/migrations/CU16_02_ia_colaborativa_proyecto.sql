-- CU16 etapa 3. Migracion aditiva e idempotente para solicitudes de IA.
-- No elimina ni reescribe datos existentes.

CREATE TABLE IF NOT EXISTS public.solicitud_ia_chat_proyecto (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id character varying(36) NOT NULL,
    proyecto_id bigint NOT NULL,
    diagrama_id bigint NOT NULL,
    mensaje_usuario_id bigint NOT NULL,
    solicitante_id bigint NOT NULL,
    mensaje_respuesta_id bigint,
    estado character varying(16) NOT NULL,
    proveedor character varying(64),
    detalle_error text,
    fecha_solicitud timestamp(6) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_finalizacion timestamp(6) without time zone,
    CONSTRAINT uk_solicitud_ia_chat_proyecto_id UNIQUE (proyecto_id, solicitud_id),
    CONSTRAINT fk_solicitud_ia_proyecto FOREIGN KEY (proyecto_id) REFERENCES public.proyecto(id),
    CONSTRAINT fk_solicitud_ia_diagrama FOREIGN KEY (diagrama_id) REFERENCES public.diagrama(id),
    CONSTRAINT fk_solicitud_ia_mensaje_usuario FOREIGN KEY (mensaje_usuario_id) REFERENCES public.mensaje_chat_proyecto(id),
    CONSTRAINT fk_solicitud_ia_solicitante FOREIGN KEY (solicitante_id) REFERENCES public.usuario(id),
    CONSTRAINT fk_solicitud_ia_respuesta FOREIGN KEY (mensaje_respuesta_id) REFERENCES public.mensaje_chat_proyecto(id),
    CONSTRAINT ck_solicitud_ia_estado CHECK (estado IN ('PROCESANDO', 'COMPLETADA', 'ERROR'))
);

CREATE INDEX IF NOT EXISTS idx_solicitud_ia_chat_proyecto_fecha
    ON public.solicitud_ia_chat_proyecto (proyecto_id, fecha_solicitud);

CREATE INDEX IF NOT EXISTS idx_solicitud_ia_chat_mensaje
    ON public.solicitud_ia_chat_proyecto (mensaje_usuario_id);
